import assert from 'node:assert/strict';
import { existsSync, mkdirSync } from 'node:fs';
import { chromium } from '@playwright/test';

const executablePath = chromium.executablePath();
assert.ok(existsSync(executablePath), 'Chromium executable must be available. Run npx playwright install chromium.');
mkdirSync('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto('http://127.0.0.1:5174', { waitUntil: 'networkidle' });
await page.locator('.book-item').first().waitFor();
assert.equal(await page.locator('.book-item').count(), 3);
assert.match(await page.title(), /墨读/);
await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });

await page.locator('#book-search').fill('不存在的书名');
assert.equal(await page.getByText('没有找到这本书').count(), 1);
await page.locator('#book-search').fill('岛屿');
assert.equal(await page.locator('.book-item').count(), 1);
await page.locator('#book-search').fill('');
await page.getByRole('button', { name: /导入小说/ }).click();
await page.locator('#novel-file').setInputFiles('tests/fixture-novel.txt');
assert.equal(await page.locator('#import-title').inputValue(), 'fixture novel');
await page.locator('#import-title').fill('山间时光');
await page.locator('#import-author').fill('许知微');
await page.getByRole('button', { name: '加入书架' }).click();
await page.getByText('《山间时光》已加入书架，开始阅读吧。').waitFor();
assert.equal(await page.locator('.book-item').count(), 4);
await page.getByRole('button', { name: '阅读《山间时光》' }).click();
assert.equal(await page.locator('.reading-chapter-title').textContent(), '第一章 山间清晨');
await page.getByRole('button', { name: '章节目录', exact: true }).click();
assert.equal(await page.locator('.chapter-link').count(), 3);
await page.locator('.chapter-link').nth(1).click();
assert.equal(await page.locator('.reading-chapter-title').textContent(), '第二章 溪边午后');
await page.getByRole('button', { name: '阅读设置', exact: true }).click();
await page.getByRole('button', { name: '静谧夜', exact: true }).click();
assert.equal(await page.locator('.reader-shell').getAttribute('data-theme'), 'night');
await page.getByRole('button', { name: '增大字号' }).click();
assert.equal(await page.locator('.reading-content').getAttribute('data-font'), '20');
await page.screenshot({ path: 'artifacts/reader-settings.png' });
await page.keyboard.press('Escape');
await page.getByRole('button', { name: '下一章', exact: true }).click();
assert.equal(await page.locator('.reading-chapter-title').textContent(), '第三章 灯下夜读');
await page.waitForTimeout(650);
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('button', { name: '阅读《山间时光》' }).click();
assert.equal(await page.locator('.reading-chapter-title').textContent(), '第三章 灯下夜读');
assert.match(await page.locator('#reader-percent').textContent(), /6[0-9]%|7[0-9]%/);
await page.getByRole('button', { name: '返回书架', exact: true }).click();
await page.getByRole('button', { name: /正在阅读/ }).click();
assert.equal(await page.locator('.book-item').count(), 1);
await page.getByRole('button', { name: /全部书籍/ }).click();
await page.getByRole('button', { name: '从书架移除《山间时光》' }).click();
await page.getByRole('button', { name: '确认移除' }).click();
await page.getByText('书籍已从服务端书架移除。').waitFor();
assert.equal(await page.locator('.book-item').count(), 3);

await page.getByRole('button', { name: /导入小说/ }).click();
await page.getByRole('tab', { name: '粘贴文本' }).click();
await page.locator('#import-title').fill('粘贴的故事');
await page.locator('#paste-text').fill('第一章 开始\n这是一个通过粘贴文本创建的故事。\n第二章 继续\n故事还有下一章。');
await page.getByRole('button', { name: '加入书架' }).click();
await page.getByText('《粘贴的故事》已加入书架，开始阅读吧。').waitFor();
assert.equal(await page.locator('.book-item').count(), 4);
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '390px page must not overflow horizontally');
await page.getByRole('button', { name: '阅读《粘贴的故事》' }).click();
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '390px reader must not overflow horizontally');
await page.getByRole('button', { name: '章节目录', exact: true }).click();
await page.locator('.chapter-link').nth(1).click();
assert.equal(await page.locator('.reading-chapter-title').textContent(), '第二章 继续');
assert.deepEqual(errors, []);
console.log('PASS: bookshelf, search, file import, paste import, chapters, settings, progress persistence, filters, delete, keyboard, and 390px responsive layout.');
await browser.close();
